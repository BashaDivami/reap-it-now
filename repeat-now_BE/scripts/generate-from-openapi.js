/**
 * Reads openapi.yml from the project root and generates:
 *   - routes/v1/index.js  (all 162 paths wired up)
 *   - data/v1/<domain>.json  (empty-array seed per domain)
 *
 * Usage:  npm run generate:v1
 *
 * REAP-specific rules applied:
 *   1. /auth/* and /msp/* are top-level domains.
 *   2. /orgs/{orgId}/<domain>/... → domain is the segment after orgId.
 *   3. Action endpoints (path:verb) → always POST, return { success: true }.
 *   4. Stream endpoints → return text/event-stream stub.
 */

const yaml = require('js-yaml');
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OPENAPI_PATH = path.join(ROOT, 'openapi.yml');
const V1_ROUTE = path.join(ROOT, 'routes', 'v1', 'index.js');
const DATA_DIR = path.join(ROOT, 'data', 'v1');

// ── Load spec ─────────────────────────────────────────────────────────────────
if (!fs.existsSync(OPENAPI_PATH)) {
  console.error('[generate:v1] openapi.yml not found in project root.');
  process.exit(1);
}
const spec = yaml.load(fs.readFileSync(OPENAPI_PATH, 'utf8'));
const allPaths = Object.keys(spec.paths || {});

// ── Helpers ───────────────────────────────────────────────────────────────────

/** /orgs/{orgId}/chat/threads → 'chat' */
function extractDomain(routePath) {
  const segs = routePath.replace(/^\//, '').split('/');
  if (segs[0] === 'auth') return 'auth';
  if (segs[0] === 'msp') return 'msp';
  if (segs[0] === 'orgs' && segs[2]) return segs[2];
  return segs[0];
}

/** /orgs/{orgId}/devices/{deviceId} → /orgs/:orgId/devices/:deviceId */
function toExpressPath(p) {
  return p.replace(/\{([^}]+)\}/g, ':$1');
}

function isActionEndpoint(p) {
  return p.includes(':') && /:[a-z]/.test(p.split('/').pop());
}

function isStreamEndpoint(p) {
  return p.endsWith('/stream');
}

function inferHandler(method, routePath) {
  if (isActionEndpoint(routePath)) return '__action';
  if (isStreamEndpoint(routePath)) return '__stream';
  const hasParam = /\{[^}]+\}/.test(routePath);
  if (method === 'get' && !hasParam) return 'getAll';
  if (method === 'get' && hasParam) return 'getOne';
  if (method === 'post') return 'create';
  if (method === 'put' || method === 'patch') return 'update';
  if (method === 'delete') return 'remove';
  return 'getAll';
}

const HTTP_METHODS = ['get', 'post', 'put', 'patch', 'delete'];

// ── Build domain → routes map ─────────────────────────────────────────────────
const domainRoutes = {}; // domain → [{expressPath, method, handler}]

for (const routePath of allPaths) {
  const domain = extractDomain(routePath);
  const expressPath = toExpressPath(routePath);
  const methods = spec.paths[routePath];

  for (const method of HTTP_METHODS) {
    if (!methods[method]) continue;
    const handler = inferHandler(method, routePath);
    if (!domainRoutes[domain]) domainRoutes[domain] = [];
    domainRoutes[domain].push({ expressPath, method, handler, routePath });
  }
}

const domains = Object.keys(domainRoutes).sort();

// ── Build routes/v1/index.js ──────────────────────────────────────────────────
const lines = [];

lines.push('/**');
lines.push(' * v1 — Auto-generated from openapi.yml (REAP API v1.3.0)');
lines.push(' * 162 paths across 32 domains.');
lines.push(' * Run `npm run generate:v1` to regenerate after spec changes.');
lines.push(' * DO NOT edit this file manually — changes will be overwritten.');
lines.push(' */');
lines.push("const router = require('express').Router();");
lines.push("const makeController = require('../../lib/makeController');");
lines.push('');

// Inline helpers for action + stream endpoints
lines.push('// Action endpoint handler (RPC-style :verb endpoints)');
lines.push('function actionHandler(label) {');
lines.push('  return (req, res) => res.json({ success: true, action: label, params: req.params });');
lines.push('}');
lines.push('');
lines.push('// SSE stream stub');
lines.push('function streamHandler(req, res) {');
lines.push("  res.setHeader('Content-Type', 'text/event-stream');");
lines.push("  res.setHeader('Cache-Control', 'no-cache');");
lines.push("  res.write('data: {\"status\":\"connected\"}\\n\\n');");
lines.push('  const t = setInterval(() => res.write(`data: {"tick":${Date.now()}}\\n\\n`), 5000);');
lines.push('  req.on("close", () => clearInterval(t));');
lines.push('}');
lines.push('');

// Declare controllers (only for domains that have CRUD handlers)
const crudDomains = domains.filter(d =>
  domainRoutes[d].some(r => !['__action', '__stream'].includes(r.handler))
);
for (const domain of crudDomains) {
  const safeName = domain.replace(/-/g, '_') + 'Ctrl';
  lines.push(`const ${safeName} = makeController('v1', '${domain}');`);
}
lines.push('');

// Mount routes per domain
for (const domain of domains) {
  const safeName = domain.replace(/-/g, '_') + 'Ctrl';
  lines.push(`// ── ${domain} ${'─'.repeat(Math.max(0, 60 - domain.length))}`);

  for (const { expressPath, method, handler, routePath } of domainRoutes[domain]) {
    if (handler === '__action') {
      const actionLabel = routePath.split(':').pop();
      lines.push(`router.${method}('${expressPath}', actionHandler('${actionLabel}'));`);
    } else if (handler === '__stream') {
      lines.push(`router.${method}('${expressPath}', streamHandler);`);
    } else {
      lines.push(`router.${method}('${expressPath}', ${safeName}.${handler});`);
    }
  }
  lines.push('');
}

lines.push('module.exports = router;');

fs.writeFileSync(V1_ROUTE, lines.join('\n'));
console.log(`[generate:v1] Written → routes/v1/index.js`);

// ── Seed data/v1/<domain>.json ────────────────────────────────────────────────
for (const domain of domains) {
  const dataFile = path.join(DATA_DIR, `${domain}.json`);
  if (!fs.existsSync(dataFile)) {
    fs.writeFileSync(dataFile, JSON.stringify([], null, 2));
    console.log(`[generate:v1] Seeded  → data/v1/${domain}.json`);
  } else {
    console.log(`[generate:v1] Skipped → data/v1/${domain}.json  (exists)`);
  }
}

console.log(`\n[generate:v1] Done — ${allPaths.length} paths, ${domains.length} domains`);
console.log('[generate:v1] Run `npm run dev` to start the server.');
